export const siteModel = {
  getContent: () => apiRequest(apiRoutes.content),
  createQuote: (quote) => apiRequest(apiRoutes.quote, { method: "POST", body: quote }),
  getAuthStatus: () => apiRequest(`${apiRoutes.auth}${apiRoutes.authStatus}`),
  setupAdmin: (email, password) => apiRequest(`${apiRoutes.auth}${apiRoutes.authSetup}`, { method: "POST", body: { email, password } }),
  login: (email, password) => apiRequest(`${apiRoutes.auth}${apiRoutes.authLogin}`, { method: "POST", body: { email, password } }),
  getSession: (token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminSession}`, { token }),
  saveContent: (content, token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminContent}`, { method: "PUT", body: content, token }),
  getAdmins: (token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminAccounts}`, { token }),
  createAdmin: (email, password, token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminAccounts}`, { method: "POST", body: { email, password }, token }),
  removeAdmin: (id, token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminAccounts}/${id}`, { method: "DELETE", token }),
  uploadMedia: (file, kind, token) => uploadMediaFile(file, kind, token),
  logout: (token) => apiRequest(`${apiRoutes.admin}${apiRoutes.adminSession}`, { method: "DELETE", token }),
};
